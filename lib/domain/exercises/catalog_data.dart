Exercise _e(
  String id,
  String name,
  MovementPattern pattern,
  List<MuscleGroup> primary, {
  List<MuscleGroup> secondary = const [],
  List<Equipment> eq = const [],
  Modality mod = Modality.strength,
  MeasurementType m = _reps,
  Mechanics mech = Mechanics.compound,
  Laterality lat = Laterality.bilateral,
  int d = 2,
  double met = 5,
  List<JointStress> js = const [],
  String? fam,
  List<String> al = const [],
  String? cues,
}) => Exercise(
  id: id,
  name: name,
  pattern: pattern,
  primaryMuscles: primary,
  secondaryMuscles: secondary,
  equipment: eq,
  modality: mod,
  measurement: m,
  mechanics: mech,
  laterality: lat,
  difficulty: d,
  met: met,
  jointStress: js,
  family: fam,
  aliases: al,
  cues: cues,
);

