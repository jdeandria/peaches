// The bundled exercise library (catalog version 1).
//
// Conventions
// * ids are stable kebab-case slugs prefixed by the primary equipment
//   (`bw-` bodyweight, `db-` dumbbell, `bb-` barbell, `kb-` kettlebell, ...).
// * difficulty 1..5 is *technical and strength* difficulty, not fatigue.
// * `met` follows the Compendium of Physical Activities where a close match
//   exists, otherwise an estimate from similar movements.
// * `family` links regressions and progressions of the same movement.
//
// Bump STANDARD_CATALOG_VERSION whenever an entry is added or reclassified.

import { Exercise } from './exercise';
import {
  Equipment,
  JointStress,
  Laterality,
  MeasurementType,
  Mechanics,
  Modality,
  MovementPattern,
  MuscleGroup,
} from './taxonomy';

export const STANDARD_CATALOG_VERSION = 1;

/** Optional fields; anything left out takes the default shown. */
interface Options {
  secondary?: MuscleGroup[]; // []
  eq?: Equipment[]; // [] (bodyweight)
  mod?: Modality; // 'strength'
  m?: MeasurementType; // 'reps'
  mech?: Mechanics; // 'compound'
  lat?: Laterality; // 'bilateral'
  d?: number; // difficulty 2
  met?: number; // 5
  js?: JointStress[]; // []
  fam?: string; // null
  al?: string[]; // []
  cues?: string; // null
}

function e(
  id: string,
  name: string,
  pattern: MovementPattern,
  primary: MuscleGroup[],
  o: Options = {},
): Exercise {
  return {
    id,
    name,
    pattern,
    primaryMuscles: primary,
    secondaryMuscles: o.secondary ?? [],
    equipment: o.eq ?? [],
    modality: o.mod ?? 'strength',
    measurement: o.m ?? 'reps',
    mechanics: o.mech ?? 'compound',
    laterality: o.lat ?? 'bilateral',
    difficulty: o.d ?? 2,
    met: o.met ?? 5,
    jointStress: o.js ?? [],
    family: o.fam ?? null,
    aliases: o.al ?? [],
    cues: o.cues ?? null,
  };
}

