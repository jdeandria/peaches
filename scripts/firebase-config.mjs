#!/usr/bin/env node
// Prepares the Firebase web config for a CI build.
//
// - If FIREBASE_WEB_CONFIG is set (the JSON object from Firebase console → Project settings →
//   Your apps → SDK setup and configuration → Config), writes it into the `firebaseConfig` object
//   in src/app/data/firebase/firebase-config.ts, leaving the rest of that file as it is.
// - Otherwise uses the committed file, failing if it still holds the placeholder values.
//
// Prints the project id and, on GitHub Actions, exposes it as the `project_id` step output.

import { appendFileSync, readFileSync, writeFileSync } from 'node:fs';

const TARGET = new URL('../src/app/data/firebase/firebase-config.ts', import.meta.url);
const TARGET_NAME = 'src/app/data/firebase/firebase-config.ts';
const CONFIG_BLOCK = /^export const firebaseConfig: FirebaseOptions = \{\n[\s\S]*?^\};$/m;
const REQUIRED = ['apiKey', 'authDomain', 'projectId', 'appId'];
const ALLOWED = [...REQUIRED, 'storageBucket', 'messagingSenderId', 'measurementId', 'databaseURL'];

function fail(message) {
  console.error(`::error::${message}`);
  process.exit(1);
}

function readConfigBlock(source) {
  const block = source.match(CONFIG_BLOCK)?.[0];
  if (!block) fail(`Could not find \`export const firebaseConfig\` in ${TARGET_NAME}`);
  return block;
}

function fromEnvironment(raw) {
  let config;
  try {
    config = JSON.parse(raw);
  } catch {
    fail(
      'FIREBASE_WEB_CONFIG must be JSON with quoted keys, e.g. ' +
        '{"apiKey":"…","authDomain":"…","projectId":"…","appId":"…"}',
    );
  }
  const missing = REQUIRED.filter((key) => typeof config[key] !== 'string' || !config[key]);
  if (missing.length) fail(`FIREBASE_WEB_CONFIG is missing: ${missing.join(', ')}`);

  const entries = ALLOWED.filter((key) => typeof config[key] === 'string').map(
    (key) => `  ${key}: ${JSON.stringify(config[key])},`,
  );
  const source = readFileSync(TARGET, 'utf8');
  readConfigBlock(source);
  const block = [
    '// Generated by scripts/firebase-config.mjs from the FIREBASE_WEB_CONFIG secret. Do not commit.',
    'export const firebaseConfig: FirebaseOptions = {',
    ...entries,
    '};',
  ].join('\n');
  writeFileSync(
    TARGET,
    source.replace(CONFIG_BLOCK, () => block),
  );
  console.log(`Wrote the firebaseConfig in ${TARGET_NAME} from FIREBASE_WEB_CONFIG`);
  return config.projectId;
}

function fromCommittedFile() {
  const block = readConfigBlock(readFileSync(TARGET, 'utf8'));
  if (/PLACEHOLDER_PROJECT_ID|peaches-not-configured|'placeholder'/.test(block)) {
    fail(
      'No Firebase config: set the FIREBASE_WEB_CONFIG secret, or commit your values to ' +
        TARGET_NAME,
    );
  }
  const projectId = block.match(/projectId:\s*['"]([^'"]+)['"]/)?.[1];
  if (!projectId) fail(`Could not find projectId in ${TARGET_NAME}`);
  console.log(`Using the committed ${TARGET_NAME}`);
  return projectId;
}

const raw = process.env.FIREBASE_WEB_CONFIG?.trim();
const projectId = raw ? fromEnvironment(raw) : fromCommittedFile();
console.log(`Firebase project: ${projectId}`);
if (process.env.GITHUB_OUTPUT)
  appendFileSync(process.env.GITHUB_OUTPUT, `project_id=${projectId}\n`);
