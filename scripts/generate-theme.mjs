#!/usr/bin/env node
// Generates the Peaches colour palette and spring-motion tokens.
//
//   node scripts/generate-theme.mjs
//
// DECISIONS #13: accents come from the M3 *fruit salad* scheme of the peach
// seed (#FFE5B4), every surface role from the hue-free *monochrome* scheme
// of the same seed. Values follow the 2021 Material colour spec.
//
// Writes:
//   src/app/ui/theme/_palette.scss  --mat-sys-* colour tokens (light + dark)
//   src/app/ui/theme/_springs.scss  --pch-spring-* easing/duration tokens
import { writeFileSync } from 'node:fs';
import { registerHooks } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// material-color-utilities 0.4 ships a few extensionless relative imports
// that Node's ESM resolver rejects; retry those with `.js`.
registerHooks({
  resolve(specifier, context, next) {
    try {
      return next(specifier, context);
    } catch (e) {
      if (specifier.startsWith('.') && !specifier.endsWith('.js')) {
        return next(`${specifier}.js`, context);
      }
      throw e;
    }
  },
});

const { argbFromHex, hexFromArgb, Hct, SchemeFruitSalad, SchemeMonochrome } =
  await import('@material/material-color-utilities');

const SEED = '#FFE5B4';
const SPEC = '2021';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'src/app/ui/theme');

/** Every colour token `mat.theme` emits → the DynamicScheme getter it reads. */
const ACCENT_ROLES = {
  primary: 'primary',
  'on-primary': 'onPrimary',
  'primary-container': 'primaryContainer',
  'on-primary-container': 'onPrimaryContainer',
  'primary-fixed': 'primaryFixed',
  'primary-fixed-dim': 'primaryFixedDim',
  'on-primary-fixed': 'onPrimaryFixed',
  'on-primary-fixed-variant': 'onPrimaryFixedVariant',
  'inverse-primary': 'inversePrimary',
  'surface-tint': 'surfaceTint',
  secondary: 'secondary',
  'on-secondary': 'onSecondary',
  'secondary-container': 'secondaryContainer',
  'on-secondary-container': 'onSecondaryContainer',
  'secondary-fixed': 'secondaryFixed',
  'secondary-fixed-dim': 'secondaryFixedDim',
  'on-secondary-fixed': 'onSecondaryFixed',
  'on-secondary-fixed-variant': 'onSecondaryFixedVariant',
  tertiary: 'tertiary',
  'on-tertiary': 'onTertiary',
  'tertiary-container': 'tertiaryContainer',
  'on-tertiary-container': 'onTertiaryContainer',
  'tertiary-fixed': 'tertiaryFixed',
  'tertiary-fixed-dim': 'tertiaryFixedDim',
  'on-tertiary-fixed': 'onTertiaryFixed',
  'on-tertiary-fixed-variant': 'onTertiaryFixedVariant',
  error: 'error',
  'on-error': 'onError',
  'error-container': 'errorContainer',
  'on-error-container': 'onErrorContainer',
  scrim: 'scrim',
};

/** Surface roles: taken from the monochrome scheme. */
const NEUTRAL_ROLES = {
  surface: 'surface',
  'on-surface': 'onSurface',
  'surface-dim': 'surfaceDim',
  'surface-bright': 'surfaceBright',
  'surface-container-lowest': 'surfaceContainerLowest',
  'surface-container-low': 'surfaceContainerLow',
  'surface-container': 'surfaceContainer',
  'surface-container-high': 'surfaceContainerHigh',
  'surface-container-highest': 'surfaceContainerHighest',
  'on-surface-variant': 'onSurfaceVariant',
  outline: 'outline',
  'outline-variant': 'outlineVariant',
  'inverse-surface': 'inverseSurface',
  'inverse-on-surface': 'inverseOnSurface',
  shadow: 'shadow',
  // Deprecated M3 roles still read by some Material components; they are
  // aliases of the surface roles, so they follow the neutral scheme too.
  background: 'surface',
  'on-background': 'onSurface',
  'surface-variant': 'surfaceContainerHighest',
};

function tokens(isDark) {
  const seed = Hct.fromInt(argbFromHex(SEED));
  const accent = new SchemeFruitSalad(seed, isDark, 0, SPEC);
  const neutral = new SchemeMonochrome(seed, isDark, 0, SPEC);
  const out = [];
  for (const [name, getter] of Object.entries(ACCENT_ROLES)) {
    out.push([name, hexFromArgb(accent[getter])]);
  }
  for (const [name, getter] of Object.entries(NEUTRAL_ROLES)) {
    out.push([name, hexFromArgb(neutral[getter])]);
  }
  // Raw palette tones mat.theme also emits (tooltips, menus).
  out.push(['neutral10', hexFromArgb(neutral.neutralPalette.tone(10))]);
  out.push(['neutral-variant20', hexFromArgb(neutral.neutralVariantPalette.tone(20))]);
  return out.sort(([a], [b]) => a.localeCompare(b));
}

const block = (isDark, indent) =>
  tokens(isDark)
    .map(([n, v]) => `${indent}--mat-sys-${n}: ${v};`)
    .join('\n');

const header = `// GENERATED by scripts/generate-theme.mjs — do not edit by hand.
// Seed ${SEED}: accents from SchemeFruitSalad, surfaces from SchemeMonochrome
// (contrast 0, ${SPEC} spec). See DECISIONS.md #13.
`;

const palette = `${header}
@mixin light {
${block(false, '  ')}
}

@mixin dark {
${block(true, '  ')}
}

:root {
  @include light;
}

@media (prefers-color-scheme: dark) {
  :root {
    @include dark;
  }
}
`;

// ---------------------------------------------------------------------------
// Springs: the M3 Expressive motion tokens (see src/app/ui/core/springs.ts).

const SPRINGS = {
  'spatial-fast': [0.6, 800],
  'spatial-default': [0.8, 380],
  'spatial-slow': [0.8, 200],
  'effects-fast': [1, 3800],
  'effects-default': [1, 1600],
  'effects-slow': [1, 800],
};

/** Position and velocity of a unit-mass spring from 0 to 1 at rest. */
function spring(ratio, stiffness) {
  const w = Math.sqrt(stiffness);
  if (ratio >= 1) {
    return (t) => {
      const e = Math.exp(-w * t);
      return [1 - e * (1 + w * t), e * w * w * t];
    };
  }
  const wd = w * Math.sqrt(1 - ratio * ratio);
  const zw = ratio * w;
  return (t) => {
    const e = Math.exp(-zw * t);
    const c = Math.cos(wd * t);
    const s = Math.sin(wd * t);
    const x = 1 - e * (c + (zw / wd) * s);
    const v = e * s * ((zw * zw) / wd + wd);
    return [x, v];
  };
}

function settleMs(ratio, stiffness) {
  const f = spring(ratio, stiffness);
  for (let ms = 16; ms < 3000; ms += 4) {
    const [x, v] = f(ms / 1000);
    if (Math.abs(x - 1) < 0.002 && Math.abs(v) < 0.02) return ms;
  }
  return 3000;
}

function linearEasing(ratio, stiffness, ms) {
  const f = spring(ratio, stiffness);
  const n = 24;
  const pts = [];
  for (let i = 0; i <= n; i++) {
    const t = i / n;
    const y = i === n ? 1 : f((t * ms) / 1000)[0];
    pts.push(+y.toFixed(4));
  }
  return `linear(${pts.join(', ')})`;
}

const springLines = [];
for (const [name, [ratio, k]] of Object.entries(SPRINGS)) {
  const ms = settleMs(ratio, k);
  springLines.push(`  --pch-spring-${name}: ${linearEasing(ratio, k, ms)};`);
  springLines.push(`  --pch-spring-${name}-duration: ${ms}ms;`);
}

const springs = `// GENERATED by scripts/generate-theme.mjs — do not edit by hand.
// M3 Expressive springs as CSS linear() easings over their settle time.
// Spatial springs (position, size, shape) overshoot slightly; effects
// springs (opacity, colour) are critically damped.

:root {
${springLines.join('\n')}
}
`;

// Keep generated files in the repo's Prettier style.
const { format, resolveConfig } = await import('prettier');
async function write(name, text) {
  const file = join(outDir, name);
  const options = (await resolveConfig(file)) ?? {};
  writeFileSync(file, await format(text, { ...options, filepath: file }));
}
await write('_palette.scss', palette);
await write('_springs.scss', springs);
console.log('Wrote _palette.scss and _springs.scss to', outDir);
